"""LaTeX tables of the thesis for the generalization study (report tables 4, 5 and 6), from the run logs.

    python scripts/thesis_tables.py --logs data/logs --out thesis/generated

Writes tab_returns.tex (test return and success rate per head and K), tab_paired.tex (paired differences J - X per seed
with 95% CI), tab_gap.tex (pool - test), and, from the noise evaluations, tab_noise.tex and tab_noise_paired.tex (report
tables 11 and 12). The cells follow the same rules as summarize_gen_pilot.py: runs gen-* and
ent-* (K=25 only for the entropy-matched heads), plus the J runs with K=inf of the earlier setup. Values are the mean of
rounds 41-50 per run, then mean +- SE over the seeds.
"""

import argparse
import fnmatch
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import summarize_noise  # noqa: E402
from summarize_gen_pilot import GEN_NAME, POOL, SEED, TEST, ci95, mean_se, read_rounds, window_mean  # noqa: E402

SUCCESS = "sample/success_rate"
KS = ("5", "25", "200", "inf")
REF_J_INF = "nav-id-hlr2e-3-detc-s*-7.5k-cpu-outer"  # J with K=inf of the setup before the generalization study
LABEL = {"nav-id": "J", "four": "Fourier", "h5": "h5", "h128": "h128", "h5-ent": "h5-ent", "h128-ent": "h128-ent"}
ORDER = ("nav-id", "four", "h5", "h128", "h5-ent", "h128-ent")
PAIRS = ("h5", "h5-ent", "h128", "h128-ent", "four")  # X in J - X


def collect(logs: Path, lo: int = 41, hi: int = 50) -> dict:
    """{(head, K): {seed: {"test", "pool", "success"}}}."""
    cells: dict = {}
    for path in sorted(logs.iterdir()):
        if not (path / "node_0.log").exists():
            continue
        m = GEN_NAME.match(path.name)
        if m:
            head = m["head"] if m["sweep"] == "gen" else f"{m['head']}-{m['sweep']}"
            key, seed = (head, m["k"]), int(m["seed"])
        elif fnmatch.fnmatch(path.name, REF_J_INF) and SEED.search(path.name):
            key, seed = ("nav-id", "inf"), int(SEED.search(path.name)[1])
        else:
            continue
        if key[0].endswith("-ent") and key[1] != "25":
            continue  # the entropy-matched controls exist only at K=25 (the K=5 one failed, see the report)
        rounds = read_rounds(path / "node_0.log")
        cells.setdefault(key, {})[seed] = {"test": window_mean(rounds, TEST, lo, hi),
                                           "pool": window_mean(rounds, POOL, lo, hi),
                                           "success": window_mean(rounds, SUCCESS, lo, hi)}
    return cells


def pm(values: list[float], digits: int = 2) -> str:
    mean, se = mean_se(values)
    return "" if math.isnan(mean) else f"${mean:.{digits}f}\\pm{se:.{digits}f}$"


def table_returns(cells: dict) -> str:
    """Mean test return +- SE (success %) per head and K. Bold: the highest mean of each column, and J at K=25."""
    rows = ["% generated by scripts/thesis_tables.py -- do not edit", "\\begin{tabular}{@{}lllll@{}}", "\\toprule",
            "testa & $K=5$ & $K=25$ & $K=200$ & $K=\\infty$ \\\\", "\\midrule"]
    best = {}
    for k in KS:
        means = {h: mean_se([s["test"] for s in cells[(h, k)].values()])[0] for h in ORDER if cells.get((h, k))}
        if means:
            best[k] = max(means, key=means.get)
    for head in ORDER:
        out = []
        for k in KS:
            seeds = cells.get((head, k))
            if not seeds:
                out.append("")
                continue
            succ = mean_se([s["success"] for s in seeds.values()])[0] * 100
            cell = f"{pm([s['test'] for s in seeds.values()])} ({succ:.0f}\\%)"
            out.append(bold(cell) if best.get(k) == head or (head, k) == ("nav-id", "25") else cell)
        rows.append(f"{LABEL[head]} & " + " & ".join(out) + " \\\\")
    return "\n".join(rows + ["\\bottomrule", "\\end{tabular}", ""])


def bold(text: str) -> str:
    """Bold text with math inside: \\textbf alone leaves the $...$ parts regular, so switch the math font too."""
    return f"\\textbf{{\\boldmath {text}}}"


def paired(cells: dict, x: str, k: str) -> str:
    j, other = cells.get(("nav-id", k)), cells.get((x, k))
    if not j or not other:
        return ""
    diffs = [j[s]["test"] - other[s]["test"] for s in sorted(set(j) & set(other))]
    mean, se = mean_se(diffs)
    lo, hi = ci95(mean, se, len(diffs))
    text = f"${mean:+.2f}$ $[{lo:.2f},\\,{hi:.2f}]$"
    return bold(text) if (lo > 0 or hi < 0) else text


def table_paired(cells: dict) -> str:
    rows = ["% generated by scripts/thesis_tables.py -- do not edit", "\\begin{tabular}{@{}lllll@{}}", "\\toprule",
            "$X$ & $K=5$ & $K=25$ & $K=200$ & $K=\\infty$ \\\\", "\\midrule"]
    for x in PAIRS:
        rows.append(f"{LABEL[x]} & " + " & ".join(paired(cells, x, k) for k in KS) + " \\\\")
    return "\n".join(rows + ["\\bottomrule", "\\end{tabular}", ""])


def table_gap(cells: dict) -> str:
    rows = ["% generated by scripts/thesis_tables.py -- do not edit", "\\begin{tabular}{@{}llll@{}}", "\\toprule",
            "testa & $K=5$ & $K=25$ & $K=200$ \\\\", "\\midrule"]
    for head in ORDER:
        out = [pm([s["pool"] - s["test"] for s in cells[(head, k)].values()]) if (head, k) in cells else "" for k in KS[:3]]
        rows.append(f"{LABEL[head]} & " + " & ".join(out) + " \\\\")
    return "\n".join(rows + ["\\bottomrule", "\\end{tabular}", ""])


def noise_reference(rows: dict) -> str:
    """Test return of J without noise (NR), reported in the caption of the noise table, not as a row: the same
    policies are evaluated on every backend, so the value must be identical across backends."""
    values = {pm([r["NR"][b] for r in rows.values()]) for b in summarize_noise.BACKENDS}
    if len(values) != 1:
        raise ValueError(f"NR differs across backends: {values}")
    return values.pop()


def table_noise(rows: dict) -> tuple[str, str]:
    """(table 11, table 12): test return of J with the effective model / full Aer, and paired differences (vs NR)."""
    backends = summarize_noise.BACKENDS
    names = {"fake_torino": "IBM Torino", "fake_brisbane": "IBM Brisbane"}
    t1 = ["% generated by scripts/thesis_tables.py -- do not edit", "\\begin{tabular}{@{}lll@{}}", "\\toprule",
          "simulazione & " + " & ".join(names[b] for b in backends) + " \\\\", "\\midrule"]
    for key, label in (("MDE", "MDE: modello depolarizzante effettivo"), ("AER", "AER: simulazione Aer completa")):
        t1.append(f"{label} & " + " & ".join(pm([r[key][b] for r in rows.values()]) for b in backends) + " \\\\")
    t2 = ["% generated by scripts/thesis_tables.py -- do not edit", "\\begin{tabular}{@{}lll@{}}", "\\toprule",
          "confronto & " + " & ".join(names[b] for b in backends) + " \\\\", "\\midrule"]
    for a, b_, label in (("AER", "NR", "AER $-$ NR"), ("AER", "MDE", "AER $-$ MDE")):
        cells = []
        for b in backends:
            diffs = [r[a][b] - r[b_][b] for r in rows.values()]
            mean, se = mean_se(diffs)
            lo, hi = ci95(mean, se, len(diffs))
            text = f"${mean:+.2f}$ $[{lo:.2f},\\,{hi:.2f}]$"
            cells.append(bold(text) if (lo > 0 or hi < 0) else text)
        t2.append(f"{label} & " + " & ".join(cells) + " \\\\")
    end = ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(t1 + end), "\n".join(t2 + end)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--logs", default="data/logs")
    ap.add_argument("--out", default="thesis/generated")
    args = ap.parse_args()
    cells = collect(Path(args.logs))
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tab_returns.tex").write_text(table_returns(cells))
    (out / "tab_paired.tex").write_text(table_paired(cells))
    (out / "tab_gap.tex").write_text(table_gap(cells))
    noise_dir = Path(__file__).resolve().parents[1] / "quantum_heads" / "analysis" / "runs" / "noise"
    t11, t12 = table_noise(summarize_noise.load(str(noise_dir), "gen-nav-id-k25-s*-7.5k-cpu-outer.json"))
    (out / "tab_noise.tex").write_text(t11)
    (out / "tab_noise_paired.tex").write_text(t12)


if __name__ == "__main__":
    main()
